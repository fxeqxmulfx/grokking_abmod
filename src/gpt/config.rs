use crate::{Result, mesh::Random};

use super::{Features, IGNORE_TARGET, MAX_CONTEXT, MAX_HEADS, MAX_ROWS, MAX_VOCAB, MAX_WIDTH};

/// Every learned channel mixer is a stack of width-preserving mesh layers.
/// A neuron reads channels c and (c + 1) mod width from the previous layer.
/// Attention always uses per-head exclusive self attention (XSA).
/// Query/key positions use full-head slice RoPE with split-half channel pairs.
/// Every block uses pre-RMSNorm, with a final RMSNorm before the vocabulary head.
/// Q/K use per-head RMS QK-Norm before RoPE; all RMSNorms are parameter-free.
/// Mesh mixers, RMSNorm, and the tied vocabulary head have no additive biases.
/// Token embeddings are generated by a mesh from fixed signed token codes.
/// Its depth equals attention_mesh_depth; every learned parameter is a mesh edge.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct GptConfig {
    pub vocab_size: usize,
    pub context: usize,
    pub width: usize,
    pub heads: usize,
    pub layers: usize,
    pub attention_mesh_depth: usize,
    pub ffn_mesh_depth: usize,
}

impl Default for GptConfig {
    fn default() -> Self {
        Self {
            vocab_size: 32,
            context: 32,
            width: 32,
            heads: 4,
            layers: 2,
            attention_mesh_depth: 4,
            ffn_mesh_depth: 6,
        }
    }
}

impl GptConfig {
    pub fn validate(&self) -> Result<()> {
        if !(2..=MAX_VOCAB).contains(&self.vocab_size) {
            return Err("vocab_size must be in 2..256".into());
        }
        if !(1..=MAX_CONTEXT).contains(&self.context) {
            return Err("context must be in 1..128".into());
        }
        if !(2..=MAX_WIDTH).contains(&self.width) {
            return Err("width must be in 2..128".into());
        }
        if !(1..=MAX_HEADS).contains(&self.heads) || !self.width.is_multiple_of(self.heads) {
            return Err("heads must be in 1..8 and divide width".into());
        }
        if !(self.width / self.heads).is_multiple_of(2) {
            return Err("slice RoPE requires an even number of channels per head".into());
        }
        if !(1..=4).contains(&self.layers) {
            return Err("layers must be in 1..4".into());
        }
        if !(1..=16).contains(&self.attention_mesh_depth)
            || !(1..=16).contains(&self.ffn_mesh_depth)
        {
            return Err("mesh depths must be in 1..16".into());
        }
        Ok(())
    }

    pub fn parameter_count(&self) -> Result<usize> {
        Ok(Layout::new(*self)?.count())
    }

    pub(crate) fn validate_tokens(&self, tokens: &[u32], sequence: usize) -> Result<()> {
        if sequence == 0
            || sequence > self.context
            || tokens.is_empty()
            || !tokens.len().is_multiple_of(sequence)
            || tokens.len() > MAX_ROWS
        {
            return Err(
                "tokens must form a nonempty batch of equal sequences within context and 4096 rows"
                    .into(),
            );
        }
        if tokens
            .iter()
            .any(|&token| token as usize >= self.vocab_size)
        {
            return Err("token ID is outside the vocabulary".into());
        }
        Ok(())
    }

    pub(crate) fn validate_batch(
        &self,
        inputs: &[u32],
        targets: &[u32],
        sequence: usize,
    ) -> Result<usize> {
        self.validate_tokens(inputs, sequence)?;
        if inputs.len() != targets.len() {
            return Err("inputs and targets must have equal lengths".into());
        }
        let mut supervised = 0;
        for &target in targets {
            if target != IGNORE_TARGET {
                if target as usize >= self.vocab_size {
                    return Err("target ID is outside the vocabulary".into());
                }
                supervised += 1;
            }
        }
        if supervised == 0 {
            return Err("batch must contain at least one supervised target".into());
        }
        Ok(supervised)
    }
}

/// AdamW hyperparameters. Learning rate may change between updates for warmup.
#[derive(Clone, Copy, Debug)]
pub struct AdamWOptions {
    pub learning_rate: f32,
    pub weight_decay: f32,
    pub beta1: f32,
    pub beta2: f32,
    pub epsilon: f32,
}

impl Default for AdamWOptions {
    fn default() -> Self {
        Self {
            learning_rate: 0.003,
            weight_decay: 0.01,
            beta1: 0.9,
            beta2: 0.999,
            epsilon: 1e-8,
        }
    }
}

impl AdamWOptions {
    pub fn validate(&self) -> Result<()> {
        if !self.learning_rate.is_finite()
            || self.learning_rate <= 0.0
            || !self.weight_decay.is_finite()
            || self.weight_decay < 0.0
            || !self.beta1.is_finite()
            || !(0.0..1.0).contains(&self.beta1)
            || !self.beta2.is_finite()
            || !(0.0..1.0).contains(&self.beta2)
            || !self.epsilon.is_finite()
            || self.epsilon <= 0.0
        {
            return Err("AdamW requires finite positive learning rate/epsilon, nonnegative decay, and betas in [0, 1)".into());
        }
        Ok(())
    }
}

#[derive(Clone, Copy, Debug)]
pub struct GptTrainOptions {
    pub steps: usize,
    pub learning_rate: f32,
    pub weight_decay: f32,
    pub report_every: usize,
}

impl Default for GptTrainOptions {
    fn default() -> Self {
        Self {
            steps: 1_000,
            learning_rate: 0.003,
            weight_decay: 0.01,
            report_every: 100,
        }
    }
}

impl GptTrainOptions {
    pub fn validate(&self) -> Result<()> {
        if self.steps == 0 || self.report_every == 0 {
            return Err("steps and report_every must be positive".into());
        }
        if !self.learning_rate.is_finite()
            || self.learning_rate <= 0.0
            || !self.weight_decay.is_finite()
            || self.weight_decay < 0.0
        {
            return Err(
                "learning_rate must be positive and weight_decay nonnegative; both must be finite"
                    .into(),
            );
        }
        Ok(())
    }
}

#[derive(Clone, Debug)]
pub(crate) struct Group {
    pub offset: usize,
    pub size: usize,
    pub depth: usize,
}

#[derive(Clone, Debug)]
pub(crate) struct Block {
    pub query: usize,
    pub key: usize,
    pub value: usize,
    pub projection: usize,
    pub ffn: usize,
}

#[derive(Clone, Debug)]
pub(crate) struct Layout {
    pub groups: Vec<Group>,
    pub blocks: Vec<Block>,
    pub embedding: usize,
}

impl Layout {
    pub(crate) fn new(config: GptConfig) -> Result<Self> {
        config.validate()?;
        let mut layout = Self {
            groups: Vec::new(),
            blocks: Vec::new(),
            embedding: 0,
        };
        layout.embedding = layout.push(config.width, config.attention_mesh_depth);
        for _ in 0..config.layers {
            let mut mesh = || layout.push(config.width, config.attention_mesh_depth);
            let query = mesh();
            let key = mesh();
            let value = mesh();
            let projection = mesh();
            let ffn = layout.push(config.width, config.ffn_mesh_depth);
            layout.blocks.push(Block {
                query,
                key,
                value,
                projection,
                ffn,
            });
        }
        Ok(layout)
    }

    fn push(&mut self, width: usize, depth: usize) -> usize {
        let id = self.groups.len();
        self.groups.push(Group {
            offset: self.count(),
            size: 2 * width * depth,
            depth,
        });
        id
    }

    pub(crate) fn count(&self) -> usize {
        self.groups
            .last()
            .map_or(0, |group| group.offset + group.size)
    }

    pub(crate) fn initialize(&self, config: GptConfig, seed: u64) -> Vec<f32> {
        let mut random = Random::new(seed);
        let mut parameters = vec![0.0; self.count()];
        for group in &self.groups {
            let values = &mut parameters[group.offset..group.offset + group.size];
            for layer in 0..group.depth {
                for channel in 0..config.width {
                    let offset = layer * 2 * config.width + channel * 2;
                    values[offset] = 0.7 + 0.2 * (random.unit() - 0.5);
                    values[offset + 1] = 0.4 * (random.unit() - 0.5);
                    // Smaller final weights stabilize embeddings and residual branches.
                    if layer + 1 == group.depth {
                        values[offset] *= 0.3;
                        values[offset + 1] *= 0.3;
                    }
                }
            }
        }
        parameters
    }
}

/// Fixed, injective token codes. Wide codes contain binary digits and bit parities.
/// At narrow widths, pack disjoint bit groups into signed radix coordinates.
/// Even width 2 can encode every supported token without collisions or zero rows.
pub(crate) fn token_codes(config: GptConfig) -> Vec<Features> {
    let bits = (usize::BITS - (config.vocab_size - 1).leading_zeros()) as usize;
    let lanes = config.width.min(bits);
    // Keep each bit first to guarantee injectivity, then add every nontrivial
    // parity before repeating. No zero mask introduces a constant coordinate.
    let masks: Vec<usize> = (0..bits)
        .map(|bit| 1 << bit)
        .chain((1..1 << bits).filter(|mask: &usize| !mask.is_power_of_two()))
        .collect();
    (0..config.vocab_size)
        .map(|token| {
            let mut code = [0.0; MAX_WIDTH];
            for (channel, value) in code[..config.width].iter_mut().enumerate() {
                if config.width >= bits {
                    *value = if (token & masks[channel % masks.len()])
                        .count_ones()
                        .is_multiple_of(2)
                    {
                        -1.0
                    } else {
                        1.0
                    };
                    continue;
                }
                let mut digit = 0;
                let mut maximum = 0;
                for bit in (channel % lanes..bits).step_by(lanes) {
                    digit = 2 * digit + ((token >> bit) & 1);
                    maximum = 2 * maximum + 1;
                }
                *value = 2.0 * digit as f32 / maximum as f32 - 1.0;
            }
            code
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn optimizer_rejects_invalid_hyperparameters() {
        let valid = AdamWOptions::default();
        for options in [
            AdamWOptions {
                beta1: 1.0,
                ..valid
            },
            AdamWOptions {
                beta2: -0.1,
                ..valid
            },
            AdamWOptions {
                beta2: f32::NAN,
                ..valid
            },
            AdamWOptions {
                epsilon: 0.0,
                ..valid
            },
            AdamWOptions {
                learning_rate: f32::INFINITY,
                ..valid
            },
            AdamWOptions {
                weight_decay: -1.0,
                ..valid
            },
        ] {
            assert!(options.validate().is_err());
        }
        AdamWOptions {
            beta1: 0.0,
            beta2: 0.98,
            ..valid
        }
        .validate()
        .unwrap();
        assert!(
            GptConfig::default()
                .validate_batch(&[0], &[IGNORE_TARGET], 1)
                .is_err()
        );
        assert_eq!(
            GptConfig::default()
                .validate_batch(&[0, 1], &[IGNORE_TARGET, 2], 2)
                .unwrap(),
            1
        );
    }

    #[test]
    fn fixed_token_codes_are_distinct_at_wide_and_narrow_widths() {
        for width in (2..=MAX_WIDTH).step_by(2) {
            for vocab_size in [2, 3, 5, 26, 129, 255, 256] {
                let config = GptConfig {
                    width,
                    vocab_size,
                    heads: 1,
                    ..GptConfig::default()
                };
                config.validate().unwrap();
                let codes = token_codes(config);
                let mut unique = std::collections::HashSet::new();
                for code in codes {
                    assert!(
                        code[..width]
                            .iter()
                            .all(|x| x.is_finite() && x.abs() <= 1.0 && *x != 0.0)
                    );
                    assert!(code[width..].iter().all(|&x| x == 0.0));
                    assert!(
                        unique.insert(code.map(f32::to_bits)),
                        "width={width} vocab={vocab_size}"
                    );
                }
                assert_eq!(unique.len(), vocab_size);
            }
        }
    }

    #[test]
    fn all_parameters_are_mesh_edges_and_do_not_grow_with_vocabulary() {
        let config = GptConfig::default();
        let expected = 2
            * config.width
            * (config.attention_mesh_depth
                + config.layers * (4 * config.attention_mesh_depth + config.ffn_mesh_depth));
        assert_eq!(expected, 3072);
        for vocab_size in [2, 26, 256] {
            let layout = Layout::new(GptConfig {
                vocab_size,
                ..config
            })
            .unwrap();
            assert_eq!(layout.count(), expected);
            assert_eq!(layout.groups.len(), 1 + 5 * config.layers);
            assert!(
                layout
                    .groups
                    .iter()
                    .all(|group| group.size == 2 * config.width * group.depth)
            );
        }
    }

    #[test]
    fn configuration_rejects_invalid_and_overflowing_dimensions() {
        let valid = GptConfig::default();
        for config in [
            GptConfig {
                width: usize::MAX,
                ..valid
            },
            GptConfig {
                vocab_size: 1,
                ..valid
            },
            GptConfig {
                context: 0,
                ..valid
            },
            GptConfig { heads: 3, ..valid },
            GptConfig {
                width: 6,
                heads: 2,
                ..valid
            },
            GptConfig {
                width: 8,
                heads: 8,
                ..valid
            },
            GptConfig { layers: 5, ..valid },
            GptConfig {
                ffn_mesh_depth: 0,
                ..valid
            },
        ] {
            assert!(config.parameter_count().is_err());
        }
        assert!(
            valid
                .validate_tokens(&[valid.vocab_size as u32], 1)
                .is_err()
        );
        assert!(valid.validate_tokens(&[], 1).is_err());
        assert!(valid.validate_batch(&[0, 1], &[1], 2).is_err());
        let maximum = GptConfig {
            width: MAX_WIDTH,
            heads: 8,
            context: 128,
            vocab_size: 256,
            layers: 4,
            attention_mesh_depth: 16,
            ffn_mesh_depth: 16,
        };
        assert!(maximum.parameter_count().unwrap() < 100_000);
    }
}
