/// Every learned channel mixer is a stack of width-preserving mesh layers.
/// A neuron reads channels c and (c + stride) mod width from the previous layer.
/// Attention always uses per-head exclusive self attention (XSA).
/// Query/key positions use full-head slice RoPE with split-half channel pairs.
/// Every block uses pre-RMSNorm, with a final RMSNorm before the vocabulary head.
/// Q/K use per-head RMS QK-Norm before RoPE; all RMSNorms are parameter-free.
/// Mesh mixers, RMSNorm, and the tied vocabulary head have no additive biases.
/// By default, token embeddings are generated by a mesh from fixed signed token
/// codes. Its depth equals attention_mesh_depth; every learned parameter is a mesh edge.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct GptConfig {
    pub vocab_size: usize,
    pub context: usize,
    pub width: usize,
    pub heads: usize,
    pub layers: usize,
    pub attention_mesh_depth: usize,
    pub ffn_mesh_depth: usize,
    pub embedding: TokenEmbedding,
    pub connectivity: MeshConnectivity,
    pub geometry: super::EmbeddingGeometry,
    pub rope: bool,
    pub qk_norm: bool,
    pub xsa: bool,
}

impl Default for GptConfig {
    fn default() -> Self {
        Self {
            vocab_size: 32,
            context: 32,
            width: 32,
            heads: 4,
            layers: 2,
            attention_mesh_depth: 4,
            ffn_mesh_depth: 6,
            embedding: TokenEmbedding::Mesh,
            connectivity: MeshConnectivity::Neighbor,
            geometry: super::EmbeddingGeometry::default(),
            rope: true,
            qk_norm: true,
            xsa: true,
        }
    }
}

/// Source of the tied vectors shared by input lookup and the vocabulary head.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum TokenEmbedding {
    /// A mesh generates every vector from fixed signed token codes.
    #[default]
    Mesh,
    /// Ablation: a learned vocabulary-by-width table. Initialization stores the
    /// vectors generated by the same seeded embedding mesh.
    Table,
}

impl TokenEmbedding {
    pub fn name(self) -> &'static str {
        match self {
            Self::Mesh => "mesh",
            Self::Table => "table",
        }
    }
}

impl fmt::Display for TokenEmbedding {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.name())
    }
}

impl FromStr for TokenEmbedding {
    type Err = String;

    fn from_str(value: &str) -> std::result::Result<Self, Self::Err> {
        match value {
            "mesh" => Ok(Self::Mesh),
            "table" => Ok(Self::Table),
            _ => Err(format!("unknown token embedding: {value}")),
        }
    }
}

/// The second parent of each mesh neuron. Both variants have two edges per neuron.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum MeshConnectivity {
    /// Every layer reads channels c and c + 1.
    #[default]
    Neighbor,
    /// Ablation: layer l reads c and c + 2^(l mod floor(log2 width)). Successive
    /// layers double the stride, so a power-of-two width mixes every channel
    /// after log2(width) layers instead of growing the window by one per layer.
    Butterfly,
}

impl MeshConnectivity {
    pub fn name(self) -> &'static str {
        match self {
            Self::Neighbor => "neighbor",
            Self::Butterfly => "butterfly",
        }
    }

    /// Distance from a neuron's own channel to its second parent; always in 1..width.
    pub(crate) fn stride(self, width: usize, layer: usize) -> usize {
        match self {
            Self::Neighbor => 1,
            Self::Butterfly => 1 << (layer % width.ilog2() as usize),
        }
    }
}

impl fmt::Display for MeshConnectivity {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.name())
    }
}

impl FromStr for MeshConnectivity {
    type Err = String;

    fn from_str(value: &str) -> std::result::Result<Self, Self::Err> {
        match value {
            "neighbor" => Ok(Self::Neighbor),
            "butterfly" => Ok(Self::Butterfly),
            _ => Err(format!("unknown mesh connectivity: {value}")),
        }
    }
}

impl GptConfig {
    pub fn validate(&self) -> Result<()> {
        if !(2..=MODEL_MAX_VOCAB).contains(&self.vocab_size) {
            return Err("vocab_size must be in 2..65536".into());
        }
        if !(1..=MODEL_MAX_CONTEXT).contains(&self.context) {
            return Err("context must be in 1..4096".into());
        }
        if !(2..=MODEL_MAX_WIDTH).contains(&self.width) {
            return Err("width must be in 2..4096".into());
        }
        if !(1..=MODEL_MAX_HEADS).contains(&self.heads) || !self.width.is_multiple_of(self.heads) {
            return Err("heads must be in 1..64 and divide width".into());
        }
        if self.width / self.heads < 2 {
            return Err("each attention head requires at least two channels".into());
        }
        if self.rope && !(self.width / self.heads).is_multiple_of(2) {
            return Err("slice RoPE requires an even number of channels per head".into());
        }
        if !(1..=64).contains(&self.layers) {
            return Err("layers must be in 1..64".into());
        }
        if !(1..=256).contains(&self.attention_mesh_depth)
            || !(1..=256).contains(&self.ffn_mesh_depth)
        {
            return Err("mesh depths must be in 1..256".into());
        }
        self.geometry.validate(*self)
    }

    pub fn parameter_count(&self) -> Result<usize> {
        Ok(Layout::new(*self)?.count())
    }

    /// Learned token-embedding parameters; they precede every block's weights.
    pub fn embedding_parameter_count(&self) -> usize {
        match self.embedding {
            TokenEmbedding::Mesh => 2 * self.width * self.attention_mesh_depth,
            TokenEmbedding::Table => self.vocab_size * self.width,
        }
    }

    /// Seeded initial weights, identical to a new CPU or CUDA model.
    pub fn initial_parameters(&self, seed: u64) -> Result<Vec<f32>> {
        let layout = Layout::new(*self)?;
        Ok(layout.initialize(*self, seed))
    }

    /// Token-vector buffers: every generated embedding-mesh layer, or the table.
    pub(crate) fn embedding_layers(&self) -> usize {
        self.raw_embedding_layers() + usize::from(self.geometry.transformed())
    }

    pub(crate) fn raw_embedding_layers(&self) -> usize {
        match self.embedding {
            TokenEmbedding::Mesh => self.attention_mesh_depth,
            TokenEmbedding::Table => 1,
        }
    }

    /// Fixed codes used by the embedding mesh or geometric table initialization.
    pub fn fixed_token_codes(&self) -> Result<Vec<Vec<f32>>> {
        self.validate()?;
        Ok(token_codes(*self))
    }

    pub(crate) fn validate_tokens(&self, tokens: &[u32], sequence: usize) -> Result<()> {
        if sequence == 0
            || sequence > self.context
            || tokens.is_empty()
            || !tokens.len().is_multiple_of(sequence)
            || tokens.len() > MAX_ROWS
        {
            return Err(format!(
                "tokens must form a nonempty batch of equal sequences within context and {MAX_ROWS} rows"
            ).into());
        }
        if tokens
            .iter()
            .any(|&token| token as usize >= self.vocab_size)
        {
            return Err("token ID is outside the vocabulary".into());
        }
        Ok(())
    }

    pub(crate) fn validate_batch(
        &self,
        inputs: &[u32],
        targets: &[u32],
        sequence: usize,
    ) -> Result<usize> {
        self.validate_tokens(inputs, sequence)?;
        if inputs.len() != targets.len() {
            return Err("inputs and targets must have equal lengths".into());
        }
        let mut supervised = 0;
        for &target in targets {
            if target != IGNORE_TARGET {
                if target as usize >= self.vocab_size {
                    return Err("target ID is outside the vocabulary".into());
                }
                supervised += 1;
            }
        }
        if supervised == 0 {
            return Err("batch must contain at least one supervised target".into());
        }
        Ok(supervised)
    }
}

/// AdamW hyperparameters. Learning rate may change between updates for warmup.
#[derive(Clone, Copy, Debug)]
pub struct AdamWOptions {
    pub learning_rate: f32,
    pub weight_decay: f32,
    pub beta1: f32,
    pub beta2: f32,
    pub epsilon: f32,
}

impl Default for AdamWOptions {
    fn default() -> Self {
        Self {
            learning_rate: 0.003,
            weight_decay: 0.01,
            beta1: 0.9,
            beta2: 0.999,
            epsilon: 1e-8,
        }
    }
}

impl AdamWOptions {
    pub fn validate(&self) -> Result<()> {
        if !self.learning_rate.is_finite()
            || self.learning_rate <= 0.0
            || !self.weight_decay.is_finite()
            || self.weight_decay < 0.0
            || !self.beta1.is_finite()
            || !(0.0..1.0).contains(&self.beta1)
            || !self.beta2.is_finite()
            || !(0.0..1.0).contains(&self.beta2)
            || !self.epsilon.is_finite()
            || self.epsilon <= 0.0
        {
            return Err("AdamW requires finite positive learning rate/epsilon, nonnegative decay, and betas in [0, 1)".into());
        }
        Ok(())
    }
}

#[derive(Clone, Copy, Debug)]
pub struct GptTrainOptions {
    pub steps: usize,
    pub learning_rate: f32,
    pub weight_decay: f32,
    pub report_every: usize,
}

impl Default for GptTrainOptions {
    fn default() -> Self {
        Self {
            steps: 1_000,
            learning_rate: 0.003,
            weight_decay: 0.01,
            report_every: 100,
        }
    }
}

impl GptTrainOptions {
    pub fn validate(&self) -> Result<()> {
        if self.steps == 0 || self.report_every == 0 {
            return Err("steps and report_every must be positive".into());
        }
        if !self.learning_rate.is_finite()
            || self.learning_rate <= 0.0
            || !self.weight_decay.is_finite()
            || self.weight_decay < 0.0
        {
            return Err(
                "learning_rate must be positive and weight_decay nonnegative; both must be finite"
                    .into(),
            );
        }
        Ok(())
    }
}

#[derive(Clone, Debug)]
pub(crate) struct Group {
    pub offset: usize,
    pub size: usize,
    pub depth: usize,
}

#[derive(Clone, Debug)]
pub(crate) struct Block {
    pub query: usize,
    pub key: usize,
    pub value: usize,
    pub projection: usize,
    pub ffn: usize,
}

#[derive(Clone, Debug)]
pub(crate) struct Layout {
    pub groups: Vec<Group>,
    pub blocks: Vec<Block>,
    pub embedding: usize,
}

impl Layout {
    pub(crate) fn new(config: GptConfig) -> Result<Self> {
        config.validate()?;
        let mut layout = Self {
            groups: Vec::new(),
            blocks: Vec::new(),
            embedding: 0,
        };
        // A table has no mesh layers; its initialization tabulates a seeded mesh.
        layout.embedding = layout.push(
            config.embedding_parameter_count(),
            match config.embedding {
                TokenEmbedding::Mesh => config.attention_mesh_depth,
                TokenEmbedding::Table => 0,
            },
        );
        for _ in 0..config.layers {
            let mut mesh = || {
                layout.push(
                    2 * config.width * config.attention_mesh_depth,
                    config.attention_mesh_depth,
                )
            };
            let query = mesh();
            let key = mesh();
            let value = mesh();
            let projection = mesh();
            let ffn = layout.push(
                2 * config.width * config.ffn_mesh_depth,
                config.ffn_mesh_depth,
            );
            layout.blocks.push(Block {
                query,
                key,
                value,
                projection,
                ffn,
            });
        }
        Ok(layout)
    }

    fn push(&mut self, size: usize, depth: usize) -> usize {
        let id = self.groups.len();
        self.groups.push(Group {
            offset: self.count(),
            size,
            depth,
        });
        id
    }

    pub(crate) fn count(&self) -> usize {
        self.groups
            .last()
            .map_or(0, |group| group.offset + group.size)
    }

    pub(crate) fn initialize(&self, config: GptConfig, seed: u64) -> Vec<f32> {
        if config.embedding == TokenEmbedding::Table {
            // Draw the same random stream as the mesh model, so both start as one function.
            let mesh = GptConfig {
                embedding: TokenEmbedding::Mesh,
                ..config
            };
            let layout = Layout::new(mesh).expect("a validated table configuration is valid");
            let mut parameters = tabulated(mesh, &layout.initialize(mesh, seed));
            if config.geometry.form != super::EmbeddingForm::Parity {
                let codes = token_codes(config);
                for (value, code) in parameters[..config.embedding_parameter_count()]
                    .iter_mut()
                    .zip(codes.into_iter().flatten())
                {
                    *value = code;
                }
            }
            return parameters;
        }
        let mut random = Random::new(seed);
        let mut parameters = vec![0.0; self.count()];
        for group in &self.groups {
            let values = &mut parameters[group.offset..group.offset + group.size];
            for layer in 0..group.depth {
                for channel in 0..config.width {
                    let offset = layer * 2 * config.width + channel * 2;
                    values[offset] = 0.7 + 0.2 * (random.unit() - 0.5);
                    values[offset + 1] = 0.4 * (random.unit() - 0.5);
                    // Smaller final weights stabilize embeddings and residual branches.
                    if layer + 1 == group.depth {
                        values[offset] *= 0.3;
                        values[offset + 1] *= 0.3;
                    }
                }
            }
        }
        for id in 0..self.groups.len() {
            let range = self.constrained_range(config, id);
            let offset = self.groups[id].offset;
            parameters[offset + range.start..offset + range.end].fill(0.0);
        }
        parameters
    }

    /// The final linear mesh rows writing protected residual coordinates.
    pub(crate) fn constrained_range(&self, config: GptConfig, id: usize) -> std::ops::Range<usize> {
        if config.geometry.preserve_features > 0
            && self
                .blocks
                .iter()
                .any(|b| b.projection == id || b.ffn == id)
        {
            let start = self.groups[id].size - 2 * config.width;
            start..start + 2 * config.geometry.preserve_features
        } else {
            0..0
        }
    }

    pub(crate) fn validate_constraints(&self, config: GptConfig, parameters: &[f32]) -> Result<()> {
        for id in 0..self.groups.len() {
            let range = self.constrained_range(config, id);
            let offset = self.groups[id].offset;
            if parameters[offset + range.start..offset + range.end]
                .iter()
                .any(|&p| p != 0.0)
            {
                return Err("protected residual output weights must be zero".into());
            }
        }
        Ok(())
    }

    pub(crate) fn mask_gradient(&self, config: GptConfig, gradient: &mut [f64]) {
        for id in 0..self.groups.len() {
            let range = if config.geometry.frozen && id == self.embedding {
                0..self.groups[id].size
            } else {
                self.constrained_range(config, id)
            };
            let offset = self.groups[id].offset;
            gradient[offset + range.start..offset + range.end].fill(0.0);
        }
    }
}

/// Converts weights of a mesh-embedding model into the matching table model. The
/// table stores the vectors the embedding mesh generates; block weights are unchanged.
pub fn tabulate_embedding(config: GptConfig, parameters: &[f32]) -> Result<Vec<f32>> {
    if config.embedding != TokenEmbedding::Mesh || parameters.len() != config.parameter_count()? {
        return Err("tabulation requires the parameters of a mesh-embedding configuration".into());
    }
    validate_finite(parameters, "parameters")?;
    let table = tabulated(config, parameters);
    validate_finite(&table, "tabulated parameters")?;
    Ok(table)
}

fn tabulated(config: GptConfig, parameters: &[f32]) -> Vec<f32> {
    let (width, depth) = (config.width, config.attention_mesh_depth);
    let mut vectors: Vec<Vec<f64>> = token_codes(config)
        .iter()
        .map(|code| code.iter().copied().map(f64::from).collect())
        .collect();
    for layer in 0..depth {
        let stride = config.connectivity.stride(width, layer);
        for vector in &mut vectors {
            let input = vector.clone();
            for (channel, value) in vector.iter_mut().enumerate() {
                let p = layer * 2 * width + 2 * channel;
                let sum = input[channel] * f64::from(parameters[p])
                    + input[(channel + stride) % width] * f64::from(parameters[p + 1]);
                *value = if layer + 1 != depth && sum < 0.0 {
                    sum.exp_m1()
                } else {
                    sum
                };
            }
        }
    }
    vectors
        .into_iter()
        .flatten()
        .map(|value| value as f32)
        .chain(
            parameters[config.embedding_parameter_count()..]
                .iter()
                .copied(),
        )
        .collect()
}

/// Fixed, injective token codes. Wide codes contain binary digits and bit parities.
/// At narrow widths, pack disjoint bit groups into signed radix coordinates.
/// Even width 2 can encode every supported token without collisions or zero rows.
pub(crate) fn token_codes(config: GptConfig) -> Vec<Vec<f32>> {
    if config.geometry.form != super::EmbeddingForm::Parity {
        return super::geometry::geometric_codes(config);
    }
    let bits = (usize::BITS - (config.vocab_size - 1).leading_zeros()) as usize;
    let lanes = config.width.min(bits);
    // Keep each bit first to guarantee injectivity, then add every nontrivial
    // parity before repeating. No zero mask introduces a constant coordinate.
    let masks: Vec<usize> = (0..bits)
        .map(|bit| 1 << bit)
        .chain((1..1 << bits).filter(|mask: &usize| !mask.is_power_of_two()))
        .collect();
    let codes = (0..config.vocab_size)
        .map(|token| {
            let mut code = vec![0.0; config.width];
            for (channel, value) in code[..config.width].iter_mut().enumerate() {
                if config.width >= bits {
                    *value = if (token & masks[channel % masks.len()])
                        .count_ones()
                        .is_multiple_of(2)
                    {
                        -1.0
                    } else {
                        1.0
                    };
                    continue;
                }
                let mut digit = 0;
                let mut maximum = 0;
                for bit in (channel % lanes..bits).step_by(lanes) {
                    digit = 2 * digit + ((token >> bit) & 1);
                    maximum = 2 * maximum + 1;
                }
                *value = 2.0 * digit as f32 / maximum as f32 - 1.0;
            }
            code
        })
        .collect();
    super::geometry::reorder_parity(config, codes)
}

#[cfg(test)]
