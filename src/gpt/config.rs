    #[test]
    fn batch_row_limit_accepts_large_batches_and_rejects_overflow() {
        let config = GptConfig::default();
        config
            .validate_tokens(&vec![0; MAX_ROWS], config.context)
            .unwrap();
        config.validate_tokens(&vec![0; MAX_ROWS - 1], 1).unwrap();
        assert!(config.validate_tokens(&vec![0; MAX_ROWS + 1], 1).is_err());
        assert!(config.validate_tokens(&[0], usize::MAX).is_err());
    }

    #[test]
    fn optimizer_rejects_invalid_hyperparameters() {
        let valid = AdamWOptions::default();
        for options in [
            AdamWOptions {
                beta1: 1.0,
                ..valid
            },
            AdamWOptions {
                beta2: -0.1,
                ..valid
            },
            AdamWOptions {
                beta2: f32::NAN,
                ..valid
            },
            AdamWOptions {
                epsilon: 0.0,
                ..valid
            },
            AdamWOptions {
                learning_rate: f32::INFINITY,
                ..valid
            },
            AdamWOptions {
                weight_decay: -1.0,
                ..valid
            },
        ] {
            assert!(options.validate().is_err());
        }
        AdamWOptions {
            beta1: 0.0,
            beta2: 0.98,
            ..valid
        }
        .validate()
        .unwrap();
        assert!(
            GptConfig::default()
                .validate_batch(&[0], &[IGNORE_TARGET], 1)
                .is_err()
        );
        assert_eq!(
            GptConfig::default()
                .validate_batch(&[0, 1], &[IGNORE_TARGET, 2], 2)
                .unwrap(),
            1
        );
    }

    #[test]
    fn fixed_token_codes_are_distinct_at_wide_and_narrow_widths() {
        let dimensions = (2..=MAX_WIDTH)
            .step_by(2)
            .flat_map(|width| [2, 3, 5, 26, 129, 255, 256].map(|vocab| (width, vocab)))
            .chain([
                (2, MODEL_MAX_VOCAB),
                (4, 1024),
                (256, 257),
                (MODEL_MAX_WIDTH, 257),
            ]);
        for (width, vocab_size) in dimensions {
            let config = GptConfig {
                width,
                vocab_size,
                heads: 1,
                ..GptConfig::default()
            };
            config.validate().unwrap();
            let mut unique = std::collections::HashSet::new();
            for code in token_codes(config) {
                assert_eq!(code.len(), width);
                assert!(
                    code.iter()
                        .all(|x| x.is_finite() && x.abs() <= 1.0 && *x != 0.0)
                );
                assert!(
                    unique.insert(code.iter().copied().map(f32::to_bits).collect::<Vec<_>>()),
                    "width={width} vocab={vocab_size}"
                );
            }
            assert_eq!(unique.len(), vocab_size);
        }
    }

