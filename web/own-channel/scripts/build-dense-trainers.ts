import {readFile} from 'node:fs/promises';
import {root} from '../project.ts';
import {PRIVATE_ADDRESSES, ROW_SLOTS} from '../src/cpu-memory.ts';
import {validateWidth} from '../src/models.ts';

// The 128-channel handwritten Dense trainer is the source. Specialize only
// widths, byte strides, addresses and parameter counts; the math is identical.
const watBase = await readFile(new URL('wasm/dense-rotary.wat', root), 'utf8');
function denseLayout(width: number) {
  const bytes = width * 4, weightBytes = (97 * width + width * width) * 4;
  let cursor = 0;
  const addresses: Record<string, number> = {};
  const allocate = (name: string, size: number) => {addresses[name] = cursor; cursor += size;};
  for (const name of ['weights', 'gradient', 'moment1', 'moment2']) allocate(name, weightBytes);
  allocate('data', 9312 * 12); allocate('samples', 512 * 4);
  allocate('readout', width * 100 * 4); allocate('readout_gradient', width * 100 * 4);
  allocate('states', ROW_SLOTS * 2 * bytes); allocate('normalized', ROW_SLOTS * 2 * bytes); allocate('branches', ROW_SLOTS * bytes);
  allocate('inverse', ROW_SLOTS * 16);
  for (const name of ['dh', 'dn', 'temporary']) allocate(name, ROW_SLOTS * bytes);
  allocate('logits', ROW_SLOTS * 400); allocate('errors', ROW_SLOTS * 400); allocate('metrics', 16); allocate('statistics', 32);
  return {addresses, cursor};
}
// The handwritten W128 header must agree with the layout generated for it.
for (const [name, address] of Object.entries(denseLayout(128).addresses)) {
  const value = ` i32 (i32.const ${address}))`;
  if (!watBase.includes(`(global $${name}${value}`) && !watBase.includes(`(global $${name} (export "${name}")${value}`)) throw new Error(`dense-rotary.wat: $${name} is not at ${address}.`);
}
export function denseWat(width: number): string {
  validateWidth(width);
  const parameters = 97 * width + width * width, bytes = width * 4;
  const {addresses, cursor} = denseLayout(width);
  const exported = new Set(['weights', 'gradient', 'data', 'samples', 'logits', 'metrics', 'statistics']);
  const globals = Object.entries(addresses).map(([name, address]) => `  (global $${name}${exported.has(name) ? ` (export "${name}")` : ''} i32 (i32.const ${address}))`);
  globals.push(`  (global $input i32 (i32.const ${addresses.states}))`, `  (global $hidden i32 (i32.const ${addresses.states + bytes}))`,
    '  (global $winner (mut i32) (i32.const 0))');
  let source = watBase.slice(watBase.indexOf('  (func $exp'));
  // Mark every W128 constant first and substitute numbers last: W32 writes
  // (i32.const 128) as a byte stride.
  source = source.replaceAll('(i32.const 49664)', '(i32.const @EMBEDDING_BYTES)')
    .replaceAll('(i32.const 128)', '(i32.const @WIDTH)').replaceAll('(f32.const 128)', '(f32.const @WIDTH)')
    .replaceAll('(i32.const 28800)', '(i32.const @PARAMETERS)').replaceAll('(i32.const 12800)', '(i32.const @READOUT)');
  // 512 is also the minibatch limit. Replace only vector byte strides/copies.
  for (const name of ['i', 'a', 'b', 'x', 'dy']) source = source.replaceAll(`(local.get $${name}) (i32.const 512)`, `(local.get $${name}) (i32.const @VECTOR_BYTES)`);
  source = source.replaceAll('(global.get $normalized) (i32.const 512)', '(global.get $normalized) (i32.const @VECTOR_BYTES)')
    .replaceAll('(local.get $a) (i32.const @VECTOR_BYTES)) (i32.const 512)', '(local.get $a) (i32.const @VECTOR_BYTES)) (i32.const @VECTOR_BYTES)')
    .replaceAll('@EMBEDDING_BYTES', String(97 * bytes)).replaceAll('@WIDTH', String(width)).replaceAll('@PARAMETERS', String(parameters))
    .replaceAll('@READOUT', String(100 * width)).replaceAll('@VECTOR_BYTES', String(bytes));
  return `;; Generated by scripts/build-dense-trainers.ts from dense-rotary.wat.
;; Shared E, Rotate90, one RMSNorm -> Dense -> ReLU residual branch, tied readout.
(module
  (memory (export "memory") ${Math.ceil(cursor / 65536)} ${Math.ceil(cursor / 65536)})
${globals.join('\n')}

${source}`;
}
export function sharedWat(source: string, width: number): string {
  const bytes = (97 * width + width * width) * 4;
  const exported = new Set(['gradient', 'samples', 'logits', 'metrics', 'statistics']);
  const privateGlobals = PRIVATE_ADDRESSES.map(name => `  (global $${name} (import "env" "${name}") i32)`).join('\n');
  return `(module
  (memory (import "env" "memory") 1 8192 shared)
${privateGlobals}
  (export "memory" (memory 0))
${[...exported].map(name => `  (export "${name}" (global $${name}))`).join('\n')}
  (global $weights (export "weights") i32 (i32.const 0))
  (global $moment1 i32 (i32.const ${bytes}))
  (global $moment2 i32 (i32.const ${2 * bytes}))
  (global $data (export "data") i32 (i32.const ${3 * bytes}))
  (global $winner (mut i32) (i32.const 0))
${source.slice(source.indexOf('  (func $exp'))}`;
}
