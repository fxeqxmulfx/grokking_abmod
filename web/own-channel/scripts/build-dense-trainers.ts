import {readFile, writeFile} from 'node:fs/promises';
import {root} from '../project.ts';
import {PRIVATE_ADDRESSES} from '../src/cpu-memory.ts';
import {MODELS} from '../src/models.ts';

// The 128-channel handwritten Dense trainer is the source. Specialize only
// widths, byte strides, addresses and parameter counts; the math is identical.
const watBase = await readFile(new URL('wasm/dense-rotary.wat', root), 'utf8');
function denseWat(width: number): string {
  const parameters = 97 * width + width * width, bytes = width * 4, weightBytes = parameters * 4;
  let cursor = 0;
  const addresses: Record<string, number> = {};
  const allocate = (name: string, size: number) => {addresses[name] = cursor; cursor += size;};
  for (const name of ['weights', 'gradient', 'moment1', 'moment2']) allocate(name, weightBytes);
  allocate('data', 9312 * 12); allocate('samples', 512 * 4);
  allocate('readout', width * 100 * 4); allocate('readout_gradient', width * 100 * 4);
  allocate('states', 2 * bytes); allocate('normalized', 2 * bytes); allocate('branches', bytes);
  allocate('inverse', 16);
  for (const name of ['dh', 'dn', 'temporary']) allocate(name, bytes);
  allocate('logits', 400); allocate('errors', 400); allocate('metrics', 16); allocate('statistics', 32);
  const exported = new Set(['weights', 'gradient', 'data', 'samples', 'logits', 'metrics', 'statistics']);
  const globals = Object.entries(addresses).map(([name, address]) => `  (global $${name}${exported.has(name) ? ` (export "${name}")` : ''} i32 (i32.const ${address}))`);
  globals.push(`  (global $input i32 (i32.const ${addresses.states}))`, `  (global $hidden i32 (i32.const ${addresses.states + bytes}))`,
    '  (global $winner (mut i32) (i32.const 0))');
  let source = watBase.slice(watBase.indexOf('  (func $exp'));
  source = source.replaceAll('(i32.const 49664)', `(i32.const ${97 * bytes})`)
    .replaceAll('(i32.const 128)', `(i32.const ${width})`).replaceAll('(f32.const 128)', `(f32.const ${width})`)
    .replaceAll('(i32.const 28800)', `(i32.const ${parameters})`).replaceAll('(i32.const 12800)', `(i32.const ${100 * width})`);
  // 512 is also the minibatch limit. Replace only vector byte strides/copies.
  for (const name of ['i', 'a', 'b', 'x', 'dy']) source = source.replaceAll(`(local.get $${name}) (i32.const 512)`, `(local.get $${name}) (i32.const ${bytes})`);
  source = source.replaceAll('(global.get $normalized) (i32.const 512)', `(global.get $normalized) (i32.const ${bytes})`)
    .replaceAll(`(local.get $a) (i32.const ${bytes})) (i32.const 512)`, `(local.get $a) (i32.const ${bytes})) (i32.const ${bytes})`);
  return `;; Generated by scripts/build-dense-trainers.ts from dense-rotary.wat.
;; Shared E, Rotate90, one RMSNorm -> Dense -> ReLU residual branch, tied readout.
(module
  (memory (export "memory") ${Math.ceil(cursor / 65536)} ${Math.ceil(cursor / 65536)})
${globals.join('\n')}

${source}`;
}
for (const {width, id: name} of Object.values(MODELS)) {
  if (width !== 128) await writeFile(new URL(`wasm/${name}.wat`, root), denseWat(width));
}

export function sharedWat(source: string, width: number): string {
  const bytes = (97 * width + width * width) * 4;
  const exported = new Set(['gradient', 'samples', 'logits', 'metrics', 'statistics']);
  const privateGlobals = PRIVATE_ADDRESSES.map(name => `  (global $${name} (import "env" "${name}") i32)`).join('\n');
  return `(module
  (memory (import "env" "memory") 1 8192 shared)
${privateGlobals}
  (export "memory" (memory 0))
${[...exported].map(name => `  (export "${name}" (global $${name}))`).join('\n')}
  (global $weights (export "weights") i32 (i32.const 0))
  (global $moment1 i32 (i32.const ${bytes}))
  (global $moment2 i32 (i32.const ${2 * bytes}))
  (global $data (export "data") i32 (i32.const ${3 * bytes}))
  (global $winner (mut i32) (i32.const 0))
${source.slice(source.indexOf('  (func $exp'))}`;
}
