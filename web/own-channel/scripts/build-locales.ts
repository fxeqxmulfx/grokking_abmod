import {mkdir, writeFile} from 'node:fs/promises';
import {root} from '../project.ts';
import {languages, rows} from './translations.ts';

const keys = new Set<string>();
for (const row of rows) {
  if (row.length !== languages.length || row.some(value => typeof value !== 'string' || !value)) throw new Error(`Incomplete translation: ${row[0]}`);
  if (keys.has(row[0])) throw new Error(`Duplicate translation: ${row[0]}`);
  keys.add(row[0]);
  const placeholders = (value: string) => Array.from(value.matchAll(/\{(\w+)\}/g), match => match[1]).sort().join(',');
  if (row.some(value => placeholders(value) !== placeholders(row[0]))) throw new Error(`Translation placeholders differ: ${row[0]}`);
}
const directory = new URL('src/locales/', root);
await mkdir(directory, {recursive: true});
for (const [index, language] of languages.entries()) {
  const dictionary = Object.fromEntries(rows.map(row => [row[0], row[index]]));
  await writeFile(new URL(`${language}.ts`, directory), '// Generated by scripts/build-locales.ts.\nexport default ' + JSON.stringify(dictionary, null, 2) + ';\n');
}
console.log(`Built ${languages.length} local catalogs with ${rows.length} messages each.`);
